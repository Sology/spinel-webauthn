# Regenerates the credentials in test/webauthn_registration.rb and
# test/webauthn_authentication.rb with the webauthn gem (3.4.3) and its
# FakeClient, a software authenticator. Run under CRuby with the gem:
#
#   ruby tools/gen_fixtures.rb   # writes fixtures.rb here
#
# then paste fixtures.rb between the configuration and the checks of each
# test, and regenerate each .expected with CRuby and the gem
# (ruby --enable-frozen-string-literal test/<name>.rb).
require "webauthn"
require "webauthn/fake_client"
require "cbor"

ORIGIN = "https://example.com"
RP_ID = "example.com"
WebAuthn.configure do |c|
  c.allowed_origins = [ORIGIN]
  c.rp_name = "Example"
  c.rp_id = RP_ID
end
enc = WebAuthn.configuration.encoder
CH_CREATE = enc.encode(("c" * 32).b)
CH_GET = enc.encode(("g" * 32).b)
CH_OTHER = enc.encode(("x" * 32).b)

def lit(obj, ind = 0)
  pad = "  " * ind
  case obj
  when Hash
    return "{}" if obj.empty?
    "{\n" + obj.map { |k, v| "#{pad}  #{k.inspect} => #{lit(v, ind + 1)}" }.join(",\n") + "\n#{pad}}"
  when Array then "[" + obj.map { |v| lit(v, ind) }.join(", ") + "]"
  else obj.inspect
  end
end

auth = WebAuthn::FakeAuthenticator.new
client = WebAuthn::FakeClient.new(ORIGIN, authenticator: auth)
reg_es = client.create(challenge: CH_CREATE)
reg_rs = client.create(challenge: CH_CREATE, credential_algorithm: "RS256")
reg_uv = client.create(challenge: CH_CREATE, user_verified: true)
reg_nup = client.create(challenge: CH_CREATE, user_present: false)
reg_wrong_rp = client.create(challenge: CH_CREATE, rp_id: "evil.example")
reg_other_origin = WebAuthn::FakeClient.new("https://evil.example", authenticator: auth).create(challenge: CH_CREATE, rp_id: RP_ID)

# packed self-attestation over the ES256 registration: the credential's own key signs
creds = auth.instance_variable_get(:@credentials)[RP_ID]
def packed_from(reg, creds, enc, tamper: false)
  att = CBOR.decode(enc.decode(reg["response"]["attestationObject"]))
  cdj = enc.decode(reg["response"]["clientDataJSON"])
  id = enc.decode(reg["rawId"])
  key = creds[id][:credential_key]
  sig = key.sign("SHA256", att["authData"] + OpenSSL::Digest::SHA256.digest(cdj))
  sig = sig.dup.tap { |s| s.setbyte(s.bytesize - 1, s.getbyte(s.bytesize - 1) ^ 1) } if tamper
  alg = key.is_a?(OpenSSL::PKey::RSA) ? -257 : -7
  packed = { "fmt" => "packed", "attStmt" => { "alg" => alg, "sig" => sig }, "authData" => att["authData"] }
  reg.merge("response" => reg["response"].merge("attestationObject" => enc.encode(CBOR.encode(packed))))
end
reg_packed = packed_from(reg_es, creds, enc)
reg_packed_rs = packed_from(reg_rs, creds, enc)
reg_packed_bad = packed_from(reg_es, creds, enc, tamper: true)

es = WebAuthn::Credential.from_create(reg_es); es.verify(CH_CREATE)
rs = WebAuthn::Credential.from_create(reg_rs); rs.verify(CH_CREATE)
get_es = client.get(challenge: CH_GET, allow_credentials: [es.id], user_handle: "handle-bytes")
get_es2 = client.get(challenge: CH_GET, allow_credentials: [es.id])
get_rs = client.get(challenge: CH_GET, allow_credentials: [rs.id])
get_es_uv = client.get(challenge: CH_GET, allow_credentials: [es.id], user_verified: true)
get_zero = client.get(challenge: CH_GET, allow_credentials: [es.id], sign_count: 0)
get_tampered = client.get(challenge: CH_GET, allow_credentials: [es.id])
sig = enc.decode(get_tampered["response"]["signature"]).dup
sig.setbyte(sig.bytesize - 1, sig.getbyte(sig.bytesize - 1) ^ 1)
get_tampered = get_tampered.merge("response" => get_tampered["response"].merge("signature" => enc.encode(sig)))
# the legacy stored form: an uncompressed P-256 point (gem <= 1.11)
pkey = WebAuthn::PublicKey.deserialize(enc.decode(es.public_key)).pkey
legacy_pk = enc.encode(pkey.public_key.to_octet_string(:uncompressed))

fixtures = {
  "CH_CREATE" => CH_CREATE, "CH_GET" => CH_GET, "CH_OTHER" => CH_OTHER,
  "REG_ES" => reg_es, "REG_RS" => reg_rs, "REG_UV" => reg_uv, "REG_NUP" => reg_nup,
  "REG_WRONG_RP" => reg_wrong_rp, "REG_OTHER_ORIGIN" => reg_other_origin,
  "REG_PACKED" => reg_packed, "REG_PACKED_RS" => reg_packed_rs, "REG_PACKED_BAD" => reg_packed_bad,
  "ES_PK" => es.public_key, "RS_PK" => rs.public_key, "LEGACY_PK" => legacy_pk,
  "GET_ES" => get_es, "GET_ES2" => get_es2, "GET_RS" => get_rs, "GET_ES_UV" => get_es_uv,
  "GET_ZERO" => get_zero, "GET_TAMPERED" => get_tampered,
}
out = +"# Generated by gen.rb with the webauthn 3.4.3 gem's FakeClient (software authenticator).\n"
fixtures.each { |k, v| out << "#{k} = #{lit(v)}\n" }
File.write("fixtures.rb", out)
puts out.bytesize
